import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('jump to page 15, validate input and preserve URL navigation', async ({ page }, testInfo) => {
  await page.goto('/history?game=mega_645&sort=asc')
  const pager = page.getByRole('navigation', { name: 'Phân trang' })
  const input = pager.getByLabel('Đến trang')
  await expect(input).toHaveValue('1')
  await input.fill('15')
  await expect(page).not.toHaveURL(/page=15/)
  await input.press('Enter')
  await expect(page).toHaveURL(/page=15/)
  await expect(pager.getByText(/Trang 15\//)).toBeVisible()
  await expect(input).toHaveValue('15')
  await expect(page).toHaveURL(/game=mega_645/)
  await expect(page).toHaveURL(/sort=asc/)
  await input.fill('99999')
  await pager.getByRole('button', { name: 'Đi', exact: true }).click()
  await expect(pager.getByRole('alert')).toContainText('Nhập số trang từ 1 đến')
  await expect(page).toHaveURL(/page=15/)
  await input.press('Escape')
  await expect(input).toHaveValue('15')
  await input.fill('2')
  await pager.getByRole('button', { name: 'Đi', exact: true }).click()
  await expect(pager.getByText(/Trang 2\//)).toBeVisible()
  await page.goBack()
  await expect(input).toHaveValue('15')
  await page.reload()
  await expect(pager.getByText(/Trang 15\//)).toBeVisible()
  await pager.scrollIntoViewIfNeeded()
  await expect
    .poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    .toBe(true)
  const accessibility = await new AxeBuilder({ page }).include('.pagination').analyze()
  expect(accessibility.violations).toEqual([])
  await pager.screenshot({ path: testInfo.outputPath('pagination.png') })
})

test('shared pagination jumps in pair analysis and resets with game context', async ({ page }) => {
  await page.goto('/pairs?game=mega_645&window=all_time')
  const pager = page.getByRole('navigation', { name: 'Phân trang' })
  await pager.getByLabel('Đến trang').fill('15')
  await pager.getByRole('button', { name: 'Đi', exact: true }).click()
  await expect(pager.getByText(/Trang 15\//)).toBeVisible()
  await page.getByLabel('Chọn game').selectOption('lotto_535')
  await expect(pager.getByText(/Trang 1\//)).toBeVisible()
  await expect(pager.getByLabel('Đến trang')).toHaveValue('1')
})
